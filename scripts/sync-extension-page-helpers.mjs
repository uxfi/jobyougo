#!/usr/bin/env node
/**
 * sync-extension-page-helpers.mjs — writes the in-page functions the Chrome
 * extension runs into extension/, where the extension can load them.
 *
 * The extension cannot use lib/ directly: its MV3 service worker only loads
 * files inside extension/, and the isolated world it injects into forbids
 * eval, so sending function source to run with `new Function` (the old
 * probe-form / eval-in-tab path) never worked — every probe came back empty.
 * lib/ stays the tested source of truth. This script writes verbatim copies,
 * and tests/extension-page-helpers.test.mjs fails whenever one is stale.
 *
 *   node scripts/sync-extension-page-helpers.mjs          rewrite the copies
 *   node scripts/sync-extension-page-helpers.mjs --check  exit 1 when stale
 */

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';
import { COLLECT_FIELDS } from '../lib/apply-collect-fields.mjs';
import {
  APPLICATION_FORM_PROBE,
  LIST_VISIBLE_NAV_BUTTONS,
  PAGE_SHOWS_APPLY_ENTRY,
  PAGE_STEP_SNAPSHOT,
} from '../lib/form-detect.mjs';
import { snapshotIdentityFields } from '../extension/apply-autofill.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// [export name, function, where its source of truth lives]
const PAGE_HELPER_SOURCES = [
  ['APPLICATION_FORM_PROBE', APPLICATION_FORM_PROBE, 'lib/form-detect.mjs'],
  ['PAGE_SHOWS_APPLY_ENTRY', PAGE_SHOWS_APPLY_ENTRY, 'lib/form-detect.mjs'],
  ['LIST_VISIBLE_NAV_BUTTONS', LIST_VISIBLE_NAV_BUTTONS, 'lib/form-detect.mjs'],
  ['PAGE_STEP_SNAPSHOT', PAGE_STEP_SNAPSHOT, 'lib/form-detect.mjs'],
  ['snapshotIdentityFields', snapshotIdentityFields, 'extension/apply-autofill.mjs'],
];

export function renderPageHelpers() {
  const blocks = PAGE_HELPER_SOURCES.map(([name, fn, from]) => {
    const src = fn.toString();
    const decl = /^(async\s+)?function\b/.test(src) ? `export ${src}` : `export const ${name} = ${src};`;
    return `// from ${from}\n${decl}\n`;
  });
  return [
    '// page-helpers.mjs — GENERATED by scripts/sync-extension-page-helpers.mjs.',
    '// Do not edit by hand: change the source function, then run',
    '// `npm run sync:extension`.',
    '//',
    '// Verbatim copies of in-page functions whose source of truth lives outside',
    '// the extension. page-helper-registry.mjs hands them to chrome.scripting as',
    '// real functions — no string eval, which the isolated world forbids.',
    '',
    blocks.join('\n'),
  ].join('\n');
}

export function renderCollectFields() {
  const src = COLLECT_FIELDS.toString();
  const body = src.slice(src.indexOf('{') + 1, src.lastIndexOf('}'));
  return [
    '// collect-fields.js — GENERATED by scripts/sync-extension-page-helpers.mjs',
    '// from COLLECT_FIELDS in lib/apply-collect-fields.mjs. Do not edit by hand:',
    '// change the lib function (tests/apply-collect-fields.test.mjs covers it),',
    '// then run `npm run sync:extension`.',
    '//',
    '// A classic script, not a module: chrome.scripting.executeScript({ files })',
    '// loads it into the tab\'s isolated world, where it defines the global',
    '// `collectFields` that a later executeScript({ func: () => collectFields() })',
    '// calls.',
    '',
    `function collectFields() {${body}}`,
    '',
  ].join('\n');
}

export const OUTPUTS = [
  ['extension/page-helpers.mjs', renderPageHelpers],
  ['extension/collect-fields.js', renderCollectFields],
];

const invoked = process.argv[1] ? resolve(process.argv[1]) : '';
const self = fileURLToPath(import.meta.url);
const isMain = process.platform === 'win32' ? invoked.toLowerCase() === self.toLowerCase() : invoked === self;

if (isMain) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [rel, render] of OUTPUTS) {
    const path = join(root, rel);
    const want = render();
    let have = '';
    try { have = readFileSync(path, 'utf8'); } catch { /* missing — write it */ }
    if (have === want) continue;
    stale.push(rel);
    if (!check) writeFileSync(path, want);
  }
  if (check && stale.length) {
    console.error(`Stale: ${stale.join(', ')} — run \`npm run sync:extension\`.`);
    process.exit(1);
  }
  console.log(stale.length ? `Updated ${stale.join(', ')}.` : 'Extension page helpers are up to date.');
}
