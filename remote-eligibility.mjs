#!/usr/bin/env node

/**
 * remote-eligibility.mjs — zero-token location/remote-eligibility annotator (#1145)
 *
 * Same annotate-never-drop contract as rank-pipeline.mjs, one column earlier
 * in the pipeline: BEFORE spending an LLM call on relevance, tag every pending
 * row with whether its already-captured LOCATION TEXT is compatible with
 * `config/profile.yml`'s `location.authorized_in`, using the deterministic
 * rule in remote-eligibility-core.mjs. It never opens a URL and never calls an
 * LLM — pure text classification over fields the scanner already wrote.
 *
 * Origin: an unsaved, one-off LLM prompt was asked to shortlist pending
 * postings by remote-international eligibility and returned 0 matches out of
 * a candidate count that did not correspond to any real file in this project.
 * By hand, the same judgment against the real pipeline found 60+ qualifying
 * postings. The rule itself was never the problem — it already lives in
 * profile.yml — nothing durable ever implemented it, so every run re-derived
 * it from scratch (or didn't) with no way to check its work. This script is
 * that rule as a tested, versioned, idempotent annotation pass, exactly like
 * rank-pipeline.mjs already is for relevance scoring.
 *
 * Written like rank-pipeline.mjs on purpose (annotate in place, sanitize with
 * sanitizeMarkdownField, write under withPipelineLock, self-test with no
 * subprocess) so the two compose: this can run first and give rank-pipeline's
 * LLM pass one less thing to guess at, or a downstream reader can just filter
 * on `location: incompatible` without spending a token.
 *
 * Usage:
 *   node remote-eligibility.mjs                # annotate every unannotated pending row
 *   node remote-eligibility.mjs --dry-run       # print annotations, write nothing
 *   node remote-eligibility.mjs --summary       # print counts by status only
 *   node remote-eligibility.mjs --self-test     # in-memory suite; touches no real files
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import * as yaml from 'js-yaml';
import { hasFlag } from './lib/cli-flags.mjs';
import { sanitizeMarkdownField } from './scan.mjs';
import { withPipelineLock } from './pipeline-lock.mjs';
import { classifyLocation } from './remote-eligibility-core.mjs';

const CAREER_OPS = dirname(fileURLToPath(import.meta.url));
const PIPELINE_PATH = join(CAREER_OPS, 'data', 'pipeline.md');
const PROFILE_PATH = join(CAREER_OPS, 'config', 'profile.yml');

const LABEL = '| location: ';
const REASON_MAX = 140;

const USAGE = `
  remote-eligibility.mjs — zero-token location/remote-eligibility annotator

  node remote-eligibility.mjs [--dry-run] [--summary]

    --dry-run     print the annotations, write nothing
    --summary     print counts by status only (compatible/incompatible/unclear)
    --self-test   run the in-memory suite (no filesystem writes, no network)
`;

/**
 * Pending, not-yet-location-annotated rows, in file order. Mirrors
 * rank-pipeline.mjs's parsePendingEntries but also keeps the location cell
 * (index 3), which that function has no reason to expose.
 *
 * @param {string} text - data/pipeline.md contents.
 * @returns {{index: number, raw: string, url: string, company: string, title: string, location: string}[]}
 */
export function parsePendingEntries(text) {
  const out = [];
  const lines = String(text ?? '').split('\n');
  lines.forEach((raw, index) => {
    if (!raw.startsWith('- [ ] ')) return;
    if (raw.includes(LABEL)) return;
    const cells = raw.slice(6).split('|').map((c) => c.trim());
    out.push({
      index,
      raw,
      url: cells[0] ?? '',
      company: cells[1] ?? '',
      title: cells[2] ?? '',
      location: cells[3] ?? '',
    });
  });
  return out;
}

/**
 * Formats one classification as the row segment, sanitizing the reason the
 * same way rank-pipeline.mjs sanitizes a model-authored one — this reason is
 * generated by this file's own fixed strings, but the location TEXT it quotes
 * inside the reason (buildCompatibleAliases matches) originated on a public
 * job board, so it is untrusted the same way a scraped title/company already
 * is (see AGENTS.md → Untrusted External Content).
 *
 * @param {'compatible'|'incompatible'|'unclear'} status
 * @param {string} reason
 * @returns {string}
 */
export function formatLocationSegment(status, reason) {
  if (!['compatible', 'incompatible', 'unclear'].includes(status)) return '';
  let clean = sanitizeMarkdownField(reason ?? '').trim();
  if (clean.length > REASON_MAX) clean = `${clean.slice(0, REASON_MAX - 1).trimEnd()}…`;
  return `location: ${status}${clean ? ` — ${clean}` : ''}`;
}

/** Idempotent: a row already carrying `| location: ` is returned unchanged. */
export function appendLocationAnnotation(rawLine, status, reason) {
  if (typeof rawLine !== 'string' || rawLine.includes(LABEL)) return rawLine;
  const segment = formatLocationSegment(status, reason);
  if (!segment) return rawLine;
  return `${rawLine} | ${segment}`;
}

/**
 * Apply pending annotations to the pipeline text. Same duplicate-row handling
 * as rank-pipeline.mjs's applyAnnotations: pipeline.md does not enforce line
 * uniqueness, so matching consumes one annotation per occurrence in file
 * order rather than keying by row text (which would give every duplicate the
 * same segment and silently drop the rest).
 *
 * @param {string} text
 * @param {{raw: string, segment: string}[]} pending
 * @returns {{text: string, written: number}}
 */
export function applyAnnotations(text, pending) {
  const queue = pending.map((a) => ({ ...a, used: false }));
  let written = 0;
  const out = String(text ?? '')
    .split('\n')
    .map((line) => {
      if (line.includes(LABEL)) return line;
      const hit = queue.find((a) => !a.used && a.raw === line);
      if (!hit) return line;
      hit.used = true;
      written += 1;
      return `${line} | ${hit.segment}`;
    })
    .join('\n');
  return { text: out, written };
}

function loadProfile(path) {
  if (!existsSync(path)) return {};
  try {
    const parsed = yaml.load(readFileSync(path, 'utf-8'));
    return parsed && typeof parsed === 'object' ? parsed : {};
  } catch {
    return {};
  }
}

async function main(args) {
  if (hasFlag(args, '--help') || hasFlag(args, '-h')) {
    console.log(USAGE);
    return 0;
  }
  if (!existsSync(PIPELINE_PATH)) {
    console.log('No data/pipeline.md yet — run a scan first. Nothing to classify.');
    return 0;
  }

  const dryRun = hasFlag(args, '--dry-run');
  const summaryOnly = hasFlag(args, '--summary');

  const profile = loadProfile(PROFILE_PATH);
  const pending = parsePendingEntries(readFileSync(PIPELINE_PATH, 'utf-8'));
  if (!pending.length) {
    console.log('No unclassified pending entries. Nothing to do.');
    return 0;
  }

  const counts = { compatible: 0, incompatible: 0, unclear: 0 };
  const annotations = [];
  for (const entry of pending) {
    const { status, reason } = classifyLocation(entry.location, profile);
    counts[status] += 1;
    const segment = formatLocationSegment(status, reason);
    if (segment) annotations.push({ raw: entry.raw, segment, entry });
  }

  console.log(`Location — Pending: ${pending.length}`);
  console.log(`  compatible:   ${counts.compatible}`);
  console.log(`  incompatible: ${counts.incompatible}`);
  console.log(`  unclear:      ${counts.unclear}`);

  if (summaryOnly) return 0;

  if (dryRun) {
    for (const { raw, segment } of annotations) console.log(`${raw} | ${segment}`);
    console.log(`\n  [dry-run] would annotate ${annotations.length} of ${pending.length} pending entr(ies).`);
    return 0;
  }

  let written = 0;
  await withPipelineLock(PIPELINE_PATH, () => {
    const current = readFileSync(PIPELINE_PATH, 'utf-8');
    const result = applyAnnotations(current, annotations);
    written = result.written;
    if (written) writeFileSync(PIPELINE_PATH, result.text);
  });

  console.log(`\n  Annotated ${written} entr(ies) of ${pending.length} pending.`);
  console.log('  Nothing was filtered, reordered, or deleted — re-read data/pipeline.md to see the tags.');
  console.log('  Next: run rank-pipeline.mjs for relevance, or filter on "location: compatible" yourself.');
  return 0;
}

// ── self-test ────────────────────────────────────────────────────────────
// Pure-function coverage. Touches no real pipeline.md, spawns no subprocess.
function selfTest() {
  let pass = 0;
  let fail = 0;
  const check = (name, cond) => {
    if (cond) {
      pass += 1;
    } else {
      fail += 1;
      console.log(`  FAIL: ${name}`);
    }
  };

  const fixture = [
    '## Pending',
    '- [ ] https://x.test/1 | Acme | Backend Engineer | Anywhere',
    '- [ ] https://x.test/2 | Beta | Android Engineer | Remote - US | posted: 2026-06-18',
    '- [x] https://x.test/3 | Gamma | Done Role | Remote',
    '- [ ] https://x.test/4 | Delta | Already Tagged | Remote | location: compatible — prior run',
    '- [ ] https://x.test/5 | Epsilon | No Location Role',
  ].join('\n');
  const pending = parsePendingEntries(fixture);
  check('skips processed rows', !pending.some((e) => e.url.endsWith('/3')));
  check('skips already-tagged rows', !pending.some((e) => e.url.endsWith('/4')));
  check('finds the three untagged candidates', pending.length === 3);
  check('parses location cell', pending[0].location === 'Anywhere');
  check('missing location cell is empty string, not undefined', pending[2].location === '');

  check('formats a compatible segment', formatLocationSegment('compatible', 'x').startsWith('location: compatible — x'));
  check('formats with no reason', formatLocationSegment('unclear', '') === 'location: unclear');
  check('unknown status yields no segment', formatLocationSegment('bogus', 'x') === '');
  check(
    'pipe in reason cannot open a column',
    !formatLocationSegment('incompatible', 'US only | remote').includes('| remote'),
  );
  check(
    'newline in reason cannot forge a row',
    !formatLocationSegment('unclear', 'x\n- [ ] fake').includes('\n'),
  );
  check('long reason truncated', formatLocationSegment('compatible', 'z'.repeat(400)).length < REASON_MAX + 30);

  const line = pending[0].raw;
  const once = appendLocationAnnotation(line, 'compatible', 'worldwide remote');
  check('annotation appends', once.endsWith('| location: compatible — worldwide remote'));
  check('annotation preserves the original line', once.startsWith(line));
  check('annotation is idempotent', appendLocationAnnotation(once, 'incompatible', 'x') === once);

  const dupText = [
    '## Pending',
    '- [ ] https://x.test/9 | Acme | Backend Engineer | Remote',
    '- [ ] https://x.test/9 | Acme | Backend Engineer | Remote',
  ].join('\n');
  const dupRaw = '- [ ] https://x.test/9 | Acme | Backend Engineer | Remote';
  const dupOut = applyAnnotations(dupText, [
    { raw: dupRaw, segment: 'location: compatible — a' },
    { raw: dupRaw, segment: 'location: unclear — b' },
  ]);
  check('both duplicate rows are annotated', dupOut.written === 2);
  check(
    'duplicates take their own segment, in order',
    dupOut.text.includes('— a') && dupOut.text.includes('— b'),
  );
  check(
    'an already-tagged row is skipped by applyAnnotations',
    applyAnnotations(`${dupRaw} | location: compatible — old`, [{ raw: dupRaw, segment: 'location: incompatible — new' }])
      .written === 0,
  );
  check(
    'a stale target is a no-op, not a corruption',
    applyAnnotations('- [ ] https://other.test | X | Y | Remote', [{ raw: dupRaw, segment: 'location: unclear — x' }])
      .written === 0,
  );

  // ── classifyLocation, against the exact postings this script exists for ──
  const profile = { location: { authorized_in: ['France', 'European Union', 'European Economic Area', 'Thailand'] } };

  check('worldwide remote is compatible', classifyLocation('Anywhere', profile).status === 'compatible');
  check('anywhere in the world is compatible', classifyLocation('Anywhere in the World', profile).status === 'compatible');
  check(
    'unspecified remote defaults compatible (profile.yml timezone_context rule)',
    classifyLocation('Remote', profile).status === 'compatible',
  );
  check('EU country + remote is compatible', classifyLocation('Berlin, Germany, Remote', profile).status === 'compatible');
  check('EMEA remote is compatible', classifyLocation('Remote - EMEA', profile).status === 'compatible');
  check('named authorized country is compatible', classifyLocation('Paris, France, Remote', profile).status === 'compatible');
  check(
    'multi-region posting compatible via its EU option',
    classifyLocation('UNITED STATES - Remote, EMEA - Remote, CANADA - Remote, LATAM - Remote', profile).status === 'compatible',
  );
  check(
    'Remote US or Remote EU is compatible',
    classifyLocation('Remote US or Remote EU', profile).status === 'compatible',
  );

  check('US-only remote is incompatible', classifyLocation('Remote - India', profile).status === 'incompatible');
  check('India-specific remote is incompatible', classifyLocation('Remote - India', profile).status === 'incompatible');
  check('US Pacific hours requirement is incompatible', classifyLocation('US-based, US Pacific hours', profile).status === 'incompatible');
  check('LATAM-restricted remote is incompatible', classifyLocation('Remote (LATAM)', profile).status === 'incompatible');
  check(
    '"(New York only)" qualifier is incompatible',
    classifyLocation('Remote (New York only)', profile).status === 'incompatible',
  );
  check(
    '"(France only)" qualifier IS compatible for an authorized candidate',
    classifyLocation('Remote (France only)', profile).status === 'compatible',
  );
  check('hybrid with no remote option is incompatible', classifyLocation('Berlin, Germany (Hybrid)', profile).status === 'incompatible');

  check('a bare city with no remote signal is unclear, not rejected', classifyLocation('Bangalore, India', profile).status === 'unclear');
  check('an empty location is unclear', classifyLocation('', profile).status === 'unclear');
  check('a whitespace-only location is unclear', classifyLocation('   ', profile).status === 'unclear');

  console.log(`\n  remote-eligibility self-test: ${pass} passed, ${fail} failed\n`);
  return fail === 0 ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  if (args.includes('--self-test')) {
    process.exit(selfTest());
  } else {
    main(args).then((code) => process.exit(code)).catch((err) => {
      console.error(err?.message ?? err);
      process.exit(1);
    });
  }
}
